const dictionaries: Record<Lang, typeof uz> = { uz, ru };
export type TKey = keyof typeof uz;

interface LangCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: TKey) => string;
}

const Ctx = createContext<LangCtx | null>(null);

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      return localStorage.getItem(STORAGE_KEY) === "ru" ? "ru" : "uz";
    } catch {
      return "uz";
    }
  });

  // Saqlangan til sahifa ochilganda ham <html lang> ga yoziladi (ekran o'quvchilar, SEO).
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(STORAGE_KEY, l);
    } catch {
      /* private rejim — til faqat shu sessiyada saqlanadi */
    }
  }, []);

  const t = useCallback((key: TKey) => dictionaries[lang][key] ?? key, [lang]);

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): LangCtx {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error("useI18n LangProvider ichida ishlatilishi kerak");
  return ctx;
}
